package main

import (
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"

	"go.yaml.in/yaml/v3"

	"github.com/aayushsss1/tidewatch/sim/scenario"
	"github.com/aayushsss1/tidewatch/sim/trace"
)

const (
	selectMinMean = 5.0
	selectMinACF  = 0.3
)

// azureSelection is the generated azure-workloads.yaml. It holds anonymized
// HashFunction values only (Azure Functions Trace 2019, CC-BY-4.0).
type azureSelection struct {
	Source    string          `yaml:"source"`
	Selector  azureSelector   `yaml:"selector"`
	Workloads []azureSelected `yaml:"workloads"`
}

type azureSelector struct {
	TopN          int     `yaml:"topN"`
	MinMeanPerMin float64 `yaml:"minMeanPerMin"`
	MinACF        float64 `yaml:"minACF"`
}

type azureSelected struct {
	Rank       int     `yaml:"rank"`
	Function   string  `yaml:"function"` // HashFunction
	P99PeakRPS float64 `yaml:"p99PeakRPS"`
	MeanRPS    float64 `yaml:"meanRPS"`
}

func selectAzureCmd(args []string, stdout io.Writer) error {
	fs := flag.NewFlagSet("select-azure", flag.ContinueOnError)
	top := fs.Int("top", 6, "number of workloads to select")
	out := fs.String("out", "", "output YAML file (required)")
	dir := fs.String("azure-dir", scenario.AzureDir(), "directory holding the Azure 2019 day files")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if *out == "" || *top < 1 {
		return errors.New("select-azure: --out and --top >= 1 are required")
	}
	ws, err := trace.LoadAzure2019(*dir, trace.Selector{TopN: *top, MinMeanPerMin: selectMinMean, MinACF: selectMinACF})
	if err != nil {
		return fmt.Errorf("%w (run scripts/bench/fetch-azure2019.sh first)", err)
	}
	sel := azureSelection{
		Source:   "Azure Functions Trace 2019 (CC-BY-4.0, Shahrad et al., USENIX ATC 2020); anonymized HashFunction values",
		Selector: azureSelector{TopN: *top, MinMeanPerMin: selectMinMean, MinACF: selectMinACF},
	}
	for i, w := range ws {
		var sum float64
		for _, c := range w.Counts {
			sum += c
		}
		sel.Workloads = append(sel.Workloads, azureSelected{
			Rank: i + 1, Function: w.ID, P99PeakRPS: round3(w.RobustPeakRPS()),
			MeanRPS: round3(sum / float64(len(w.Counts)) / 60),
		})
	}
	data, err := yaml.Marshal(sel)
	if err != nil {
		return err
	}
	header := "# Generated by `tidewatch-bench select-azure --top " + fmt.Sprint(*top) + "`; do not edit.\n"
	if err := os.MkdirAll(filepath.Dir(*out), 0o750); err != nil {
		return err
	}
	if err := os.WriteFile(*out, append([]byte(header), data...), 0o644); err != nil { //nolint:gosec // committed file
		return err
	}
	_, _ = fmt.Fprintf(stdout, "wrote %d workloads to %s\n", len(sel.Workloads), *out)
	return nil
}

func round3(v float64) float64 { return float64(int64(v*1000+0.5)) / 1000 }
